/// Tabular digit advance of the value face (4 is a little narrower).
const TABULAR_DIGIT: f32 = 6.7109;
const TABULAR_FOUR: f32 = 6.6953;

fn advance(table: &[(char, f32)], c: char) -> f32 {
    let find = |c: char| table.binary_search_by(|e| e.0.cmp(&c)).ok().map(|i| table[i].1);
    find(c).or_else(|| find('M')).unwrap_or(0.0)
}

/// Caption text (picker names), before rounding.
pub fn name_width(text: &str) -> f32 {
    text.chars().map(|c| advance(&NAME_ADVANCE, c) + 0.2).sum()
}

/// Value text (menu pills, latches).
pub fn value_width(text: &str) -> f32 {
    text.chars().map(|c| advance(&VALUE_ADVANCE, c) - 0.4).sum()
}

/// Choice text (segments): the value face with tabular digits.
pub fn choice_width(text: &str) -> f32 {
    text.chars()
        .map(|c| match c {
            '4' => TABULAR_FOUR,
            '0'..='9' => TABULAR_DIGIT,
            _ => advance(&VALUE_ADVANCE, c),
        } - 0.4)
        .sum()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted_and_measure() {
        assert!(NAME_ADVANCE.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(VALUE_ADVANCE.windows(2).all(|w| w[0].0 < w[1].0));
        assert!((choice_width("12") - 2.0 * (TABULAR_DIGIT - 0.4)).abs() < 1e-4);
        assert_eq!(value_width("\u{2603}"), value_width("M"));
    }
}
